/**
 * The icons a block can name (`defineBlock({ icon })`), by their Lucide name. The editor is
 * built once and served ready-made, so it carries a set that covers the usual kinds of section
 * and not all of Lucide. A name outside the set gets the plain icon; add to the set on request.
 */
const icons: Readonly<Record<string, LucideIcon>> = {
  'align-left': AlignLeft,
  'badge-check': BadgeCheck,
  blocks: Blocks,
  'building-2': Building2,
  'calendar-days': CalendarDays,
  'chart-no-axes-column': ChartNoAxesColumn,
  'circle-help': CircleHelp,
  'columns-2': Columns2,
  'columns-3': Columns3,
  contact: Contact,
  'gallery-horizontal': GalleryHorizontal,
  hash: Hash,
  heading: Heading,
  house: House,
  image: Image,
  images: Images,
  'layout-grid': LayoutGrid,
  'layout-list': LayoutList,
  'layout-template': LayoutTemplate,
  list: List,
  'list-checks': ListChecks,
  mail: Mail,
  'map-pin': MapPin,
  megaphone: Megaphone,
  'message-circle': MessageCircle,
  'message-square-quote': MessageSquareQuote,
  'mouse-pointer-click': MousePointerClick,
  newspaper: Newspaper,
  'panel-top': PanelTop,
  phone: Phone,
  play: Play,
  quote: Quote,
  'rows-3': Rows3,
  sparkles: Sparkles,
  star: Star,
  table: Table,
  tag: Tag,
  text: Text,
  type: Type,
  users: Users,
};

/** The icon for a block, or the plain one when it names none the editor carries. */
export function blockIcon(name: string | undefined): LucideIcon {
  return (name !== undefined ? icons[name] : undefined) ?? Blocks;
}
