// Writes src/migrations.generated.ts from the migrations folder, so a host with no disk can run them.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../migrations/', import.meta.url);
const journal = JSON.parse(readFileSync(new URL('meta/_journal.json', dir), 'utf8'));
const list = journal.entries.map((entry) => {
  const query = readFileSync(new URL(`${entry.tag}.sql`, dir), 'utf8');
  return {
    tag: entry.tag,
    when: entry.when,
    hash: createHash('sha256').update(query).digest('hex'),
    statements: query.split('--> statement-breakpoint'),
  };
});
const module = `// Generated by scripts/bundle-migrations.mjs from migrations/. Do not edit.
export interface BundledMigration {
  readonly tag: string;
  readonly when: number;
  readonly hash: string;
  readonly statements: readonly string[];
}

export const MIGRATIONS: readonly BundledMigration[] = ${JSON.stringify(list, null, 2)};
`;
// `--print` is for the test that fails while the module is stale.
if (process.argv.includes('--print')) process.stdout.write(module);
else {
  writeFileSync(new URL('../src/migrations.generated.ts', import.meta.url), module);
  console.log(`Bundled ${list.length} migrations into src/migrations.generated.ts.`);
}
